import io
import os
import logging
from datetime import datetime
from docx import Document
from docx.shared import Inches, Pt, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH

logger = logging.getLogger(__name__)


class DOCXGenerator:
    @staticmethod
    def generate(document_text: str, document_type: str, logo_path: str = None) -> bytes:
        """Generate DOCX file content."""
        try:
            doc = Document()

            # Add logo if available
            if logo_path and os.path.exists(logo_path):
                doc.add_picture(logo_path, width=Inches(1.5))
                doc.paragraphs[-1].alignment = WD_ALIGN_PARAGRAPH.CENTER

            # Add title
            title = doc.add_heading(document_type.upper(), 0)
            title.alignment = WD_ALIGN_PARAGRAPH.CENTER

            # Add generation date
            date_para = doc.add_paragraph()
            date_para.add_run(f"Generated: {datetime.now().strftime('%B %d, %Y')}").italic = True
            date_para.alignment = WD_ALIGN_PARAGRAPH.CENTER

            doc.add_paragraph()

            # Add document content
            lines = document_text.split('\n')
            for line in lines:
                line = line.strip()
                if not line:
                    continue
                if line.startswith('# '):
                    doc.add_heading(line[2:], level=1)
                elif line.startswith('## '):
                    doc.add_heading(line[3:], level=2)
                elif line.startswith('### '):
                    doc.add_heading(line[4:], level=3)
                else:
                    doc.add_paragraph(line)

            # Add footer
            section = doc.sections[0]
            footer = section.footer
            footer_para = footer.paragraphs[0]
            footer_para.text = "Generated by LegalEase - AI-Powered Legal Document Generator"
            footer_para.alignment = WD_ALIGN_PARAGRAPH.CENTER

            # Save to bytes
            buffer = io.BytesIO()
            doc.save(buffer)
            buffer.seek(0)
            return buffer.getvalue()

        except Exception as e:
            logger.error(f"DOCX generation error: {str(e)}")
            raise ValueError("Failed to generate DOCX file")
